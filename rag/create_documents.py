def create_documents():
    """Create synthetic healthcare documents if they do not already exist."""
    created_files = []
    for domain, files in DOCUMENTS.items():
        domain_dir = BASE_DIR / "documents" / domain
        domain_dir.mkdir(parents=True, exist_ok=True)

        for filename, content in files.items():
            file_path = domain_dir / filename
            if not file_path.exists():
                file_path.write_text(content, encoding="utf-8")
                created_files.append(str(file_path.relative_to(BASE_DIR)))

    if created_files:
        print(f"Created files: {', '.join(created_files)}")
    else:
        print("All domain documents already exist; no new files were created.")

    return created_files


